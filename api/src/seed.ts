async function main() {
  console.log('Seeding database with demo papers...')
  
  // Wipe existing papers
  await prisma.paper.deleteMany()
  console.log('Cleared existing papers.')

  // Insert 10 fictional demo papers
  for (const paper of demoPapers) {
    await prisma.paper.create({
      data: {
        ...paper,
        status: 'PENDING',
      },
    })
  }

  console.log(`Successfully seeded ${demoPapers.length} fictional papers (all PENDING).`)
}

main()
  .catch((e) => {
    console.error('Failed to seed database:', e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
